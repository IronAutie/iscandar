/* LargeRowsDriver.c -- row driver for Large requests
   Blackboard 2026-10-25/26, rederived from requirements, not
   ported from the APL listings.
   Portable: EXPORT is empty on non-Windows, so this compiles
   with gcc on Linux for testing as well as with cl on Windows.
   Status codes come from status.h, generated by gen_status.py.
   GEAR_SUCCESS = 8, GEAR_FAIL = 1, GEAR_EXHAUST = 2.
*/
#include <stdint.h>
#include "status.h"
#ifdef _WIN32
#define EXPORT __declspec(dllexport)
#else
#define EXPORT
#endif
#define ARITY 32u
#define PLANES 32u
#define ROWS_TOTAL 1024u
#define SECTORS_PER_PLANE 1024u

static uint32_t trailing_run(uint32_t word) {
    uint32_t run = 0;
    int sector;
    for (sector = 31; sector >= 0; sector--) {
        if (((word >> sector) & 1u) == 0) run++; else break;
    }
    return run;
}
static uint32_t leading_run(uint32_t word) {
    uint32_t run = 0;
    uint32_t sector;
    for (sector = 0; sector < 32u; sector++) {
        if (((word >> sector) & 1u) == 0) run++; else break;
    }
    return run;
}

/* Probe for one core start. Core blankness is NOT checked here:
   the caller guarantees it with the rolling window sum.
   This probe does only the three head/tail scenarios, and
   returns GEAR_SUCCESS with the start coordinate, or
   GEAR_FAIL. core_start is a global row index. */
static int32_t large_probe(uint32_t core_start, uint32_t request,
                           const uint32_t *words,
                           uint32_t *plane_out, uint32_t *row_out,
                           uint32_t *sector_out) {
    uint32_t core = request / ARITY;
    uint32_t remainder = request % ARITY;
    uint32_t head_row, tail_row, head_len, head_take, remaining;
    if (remainder == 0) {
        *plane_out = core_start / ARITY;
        *row_out = core_start % ARITY;
        *sector_out = 0;
        return GEAR_SUCCESS;
    }
    head_row = core_start - 1;
    tail_row = core_start + core;
    if (core_start == 0) {
        if (tail_row >= ROWS_TOTAL) return GEAR_FAIL;
        if (leading_run(words[tail_row]) < remainder) return GEAR_FAIL;
        *plane_out = core_start / ARITY;
        *row_out = core_start % ARITY;
        *sector_out = 0;
        return GEAR_SUCCESS;
    }
    if (core_start + core - 1 == 1023u) {
        if (head_row >= ROWS_TOTAL) return GEAR_FAIL;
        if (trailing_run(words[head_row]) < remainder) return GEAR_FAIL;
        *plane_out = head_row / ARITY;
        *row_out = head_row % ARITY;
        *sector_out = 32u - remainder;
        return GEAR_SUCCESS;
    }
    head_len = trailing_run(words[head_row]);
    head_take = head_len < remainder ? head_len : remainder;
    remaining = remainder - head_take;
    if (remaining == 0) {
        *plane_out = head_row / ARITY;
        *row_out = head_row % ARITY;
        *sector_out = 32u - head_take;
        return GEAR_SUCCESS;
    }
    if (tail_row >= ROWS_TOTAL) return GEAR_FAIL;
    if (leading_run(words[tail_row]) < remaining) return GEAR_FAIL;
    if (head_take > 0) {
        *plane_out = head_row / ARITY;
        *row_out = head_row % ARITY;
        *sector_out = 32u - head_take;
    } else {
        *plane_out = core_start / ARITY;
        *row_out = core_start % ARITY;
        *sector_out = 0;
    }
    return GEAR_SUCCESS;
}

