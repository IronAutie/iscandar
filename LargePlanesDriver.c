static uint32_t trailing_run(uint32_t word) {
    uint32_t run = 0;
    int sector;
    for (sector = 31; sector >= 0; sector--) {
        if (((word >> sector) & 1u) == 0) run++; else break;
    }
    return run;
}
static uint32_t leading_run(uint32_t word) {
    uint32_t run = 0;
    uint32_t sector;
    for (sector = 0; sector < 32u; sector++) {
        if (((word >> sector) & 1u) == 0) run++; else break;
    }
    return run;
}

